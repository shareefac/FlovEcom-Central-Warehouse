-- 0009_suppliers.sql — Inventory Phase I-2, task 1 (IM4): settings, VAT codes, suppliers, supplier items, price history and
-- the ERPNext seed-import runs (docs/decisions.md I38-I47).
--
--  * app_setting: typed settings (CW\Settings). READ-ONLY for cw_app; bin/settings.php --admin changes them (audit
--    setting.change). The company.* rows are empty placeholders until the owner provides the details (decision 9,
--    provisional): every PO PDF carries a "not confirmed - do not send" banner while company.confirmed is false.
--  * vat_code: the VAT codes a PO line carries (read-only, changed by migration).
--  * supplier: no bank, IBAN, sort-code or account column (decision 25, provisional: a test asserts it). A new or
--    re-activated supplier is active only after a second person approves it (review_task subject 'supplier', kind
--    approval, decision 11, provisional); identity changes of an active supplier open a non-blocking review.
--  * supplier_item: what a supplier sells us, pack -> central units; one preferred supplier item per item (the generated
--    preferred_sku_id + UNIQUE); last price mirrors the newest non-PO price history row (S4).
--  * supplier_item_price: price history, append-only for cw_app.
--  * import_run: one row per ERPNext seed file (backup copy only, decision 4); a file is imported once (sha256).
-- No backfill: every table starts empty except the seeded settings and VAT codes.

CREATE TABLE app_setting (
  setting_key   VARCHAR(64)  NOT NULL,
  value_type    ENUM('string','text','int','decimal','bool','date') NOT NULL,
  value_json    JSON         NOT NULL COMMENT 'JSON string/number/boolean; "" = not set',
  provisional   TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '1 = a default the owner has not confirmed',
  decision      VARCHAR(16)  NULL COMMENT 'owner decision (inventory plan §10) it implements',
  description   VARCHAR(500) NOT NULL,
  updated_actor VARCHAR(64)  NOT NULL DEFAULT 'system:migrate',
  updated_at    DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (setting_key),
  CONSTRAINT ck_app_setting_key CHECK (REGEXP_LIKE(setting_key, '^[a-z][a-z0-9_]*([.][a-z][a-z0-9_]*)+$', 'c')),
  CONSTRAINT ck_app_setting_flags CHECK (provisional IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
  COMMENT='settings: read-only for cw_app; bin/settings.php --admin changes them (audit setting.change)';
