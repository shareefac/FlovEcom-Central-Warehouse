CREATE TABLE vat_code (
  code          VARCHAR(4)   NOT NULL,
  label         VARCHAR(64)  NOT NULL,
  rate_percent  DECIMAL(5,2) NOT NULL,
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  sort_order    SMALLINT UNSIGNED NOT NULL DEFAULT 100,
  PRIMARY KEY (code),
  CONSTRAINT ck_vat_code_code CHECK (REGEXP_LIKE(code, '^[A-Z]{1,4}$', 'c')),
  CONSTRAINT ck_vat_code_rate CHECK (rate_percent >= 0 AND rate_percent <= 100),
  CONSTRAINT ck_vat_code_flags CHECK (is_active IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='VAT codes on PO lines (read-only, changed by migration)';
